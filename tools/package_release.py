# -*- coding: utf-8 -*-
"""Assemble a clean, publishable tree for GitHub.

Copies only shipping files, then runs a leak audit over the result. Anything
machine-specific (config with API keys, project progress, caches, build
intermediates, absolute paths) must never reach the output.

Usage:
    python tools/package_release.py            # build ./release
    python tools/package_release.py --dest DIR
"""

from __future__ import annotations

import argparse
import os
import pathlib
import re
import shutil
import stat
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

# --- what ships -----------------------------------------------------------
